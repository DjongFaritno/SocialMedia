const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const version = require('../package.json').version;
const imageName = 'DuoChat-' + version + '.AppImage';
const image = fs.readFileSync(path.join('dist', imageName));
const hash = crypto.createHash('sha256').update(image).digest('hex');
assert.match(version, /^\d+\.\d+\.\d+(?:-[\w.-]+)?$/, 'Invalid application version');
let script = fs.readFileSync('scripts/install-fedora.template.sh', 'utf8');
assert.ok(script.includes('@VERSION@') && script.includes('@APPIMAGE_SHA256@'), 'Installer template placeholders missing');
script = script.replaceAll('@VERSION@', version).replaceAll('@APPIMAGE_SHA256@', hash);
assert.ok(!/@(?:VERSION|APPIMAGE_SHA256)@/.test(script), 'Unresolved installer placeholder');
assert.ok(script.includes("expected_sha='" + hash + "'"));
assert.ok(script.includes("app_name='" + imageName + "'"));
fs.writeFileSync('dist/install-fedora.sh', script, { mode: 0o755 });
console.log('Fedora installer prepared for ' + version + ', checksum ' + hash);
